sorun = []
kom = []
for r in rows:
    if not re.match(r'^\d+:\d+$', r['nitelik_ayet']):
        sorun.append(('ayet_biçimi', r['nitelik_ayet'], r['blok'], r['ham']))
        continue
    s, a = map(int, r['nitelik_ayet'].split(':'))
    if (s, a) not in body:
        sorun.append(('ayet_yok', r['nitelik_ayet'], r['blok'], r['ham']))
        continue
    metin = ' '.join(fold(n) for _, n in toks(s, a))
    komsu = metin
    for d in (-1, 1):
        if (s, a + d) in body:
            komsu += ' ' + ' '.join(fold(n) for _, n in toks(s, a + d))
    for k in esle(r['ham']):
        if k in KOK and not re.search(fold(KOK[k]), metin):
            if re.search(fold(KOK[k]), komsu):
                kom.append((k, r['nitelik_ayet'], r['ham']))
            else:
                sorun.append(('kök_yok', k, r['nitelik_ayet'], r['blok'], r['ham']))
    if r['odul_ayet'] not in H:
        sorun.append(('ceza_isareti_yok', r['odul'], r['odul_ayet'], r['blok'], r['ham']))
print(len(sorun), 'komşu ayette kök bulunan:', len(set(kom)))
for x in sorun:
    print(*x, sep=' | ')
