def next_bigram(ts):
    out = []
    for i in range(len(ts) - 1):
        a, b = fold(ts[i][1]), fold(ts[i + 1][1])
        if re.fullmatch(r'[وف]?اصحب', a) and re.fullmatch(r'(?:الجنة|النار|الجحيم|السعير|اليمين|الشمال|الميمنة|المشامة|المشمة|الاعراف|الحجر|الايكة|مدين|الفيل|الرس|السبت|الكهف)', b):
            out.append(ts[i][1] + ' ' + ts[i + 1][1])
    return out

