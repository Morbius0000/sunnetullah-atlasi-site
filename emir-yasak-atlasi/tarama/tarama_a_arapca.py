def run():
    out = {}
    for k in sorted(verses):
        if k == (1, 1): continue
        ts = toks(*k)
        hit = collections.defaultdict(list)
        for w, n in ts:
            nf = fold(n)
            for f, rx in FAM.items():
                if rx is not None and (rx.match(n) or rx.match(nf)): hit[f].append(n)
            if plural_imperative(w, n): hit['emir_kipi'].append(w)
            if HITAP.match(nf): hit['hitap'].append(nf)
            if SING.match(nf): hit['emir_tekil'].append(nf)
        # كتب عليكم / كتب علينا ...
        for i, (w, n) in enumerate(ts):
            if re.fullmatch(r'[وف]?كتب', n) and any(re.fullmatch(r'عليكم|عليهم|عليه|علينا|عليكما|عليهن', m) for _, m in ts[i+1:i+4]):
                hit['kutiba_alaykum'].append(n)
        bg = next_bigram(ts)
        if bg: hit['ashab_kaliplari'] = bg
        pr = prohibition(ts)
