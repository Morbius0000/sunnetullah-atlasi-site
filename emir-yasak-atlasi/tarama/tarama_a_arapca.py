NO = {'تلك','تلكم','تحت','تلقاء','يا','تلكما'}
def last_diac(w):
    i = len(w) - 1
    while i >= 0 and not _L(w[i]): i -= 1
    j = i + 1
    return ''.join(c for c in w[j:] if c in '\u064b\u064c\u064d\u064e\u064f\u0650\u0651\u0652')
def prohibition(ts):
    """lā + cezm (2./3. kişi): 'لا تقتلوا', 'ولا تقربوا', 'ألا تعبدوا' vb."""
    out = []
    for i in range(len(ts) - 1):
        w, n = ts[i]; w2, n2 = ts[i + 1]
        if re.fullmatch(r'[وف]?لا', n) and n2 not in NO and len(n2) >= 3 and n2[0] in 'تي':
            jus = n2.endswith('وا') or (not n2.endswith(('ون', 'ان', 'ين', 'ن')) and last_diac(w2) in ('', '\u0652'))
            if jus: out.append(w + ' ' + w2)
        if n == 'الا' and re.match(r'^[تي]', n2) and n2.endswith('وا') and n2 not in NO:   # 'أَلَّا تَعْبُدُوا'
            out.append(w + ' ' + w2)
    return out
def fold(n): return n.replace('أ','ا').replace('إ','ا').replace('آ','ا').replace('ؤ','و').replace('ئ','ي').replace('ء','')
DIAC_FATHA, DIAC_DAMMA, DIAC_KASRA = '\u064e', '\u064f', '\u0650'
def letters_diac(w):
    out = []
    for c in w:
        if _L(c): out.append([c, ''])
        elif out and c in '\u064b\u064c\u064d\u064e\u064f\u0650\u0651\u0652': out[-1][1] += c
    return out
def plural_imperative(w, n):
    """Çoğul emir kipine benzeyen fiil (düşük kesinlik; yalnız aday toplamak için)."""
    if not n.endswith('وا') or len(n) < 4 or n[0] in 'يتن' and not w.startswith('\u0671'): return False
    C = letters_diac(w)
    while C and C[-1][0] in 'وا' and not C[-1][1]: C.pop()
    if len(C) < 2 or DIAC_DAMMA not in C[-1][1]: return False
    prev = C[-2]
    if DIAC_KASRA in prev[1] or DIAC_DAMMA in prev[1]: return True
    if prev[0] in 'اوي' and not prev[1] and len(C) >= 3 and (DIAC_DAMMA in C[-3][1] or DIAC_KASRA in C[-3][1]): return True
    return False

